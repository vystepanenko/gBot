package bot

import (
	telebot "gopkg.in/telebot.v4"
)

var (
	conversationMenu = &telebot.ReplyMarkup{}
	secretMenu       = &telebot.ReplyMarkup{}
	btnYes           = conversationMenu.Data("Yes", "conversation_yes")
	btnNo            = conversationMenu.Data("No", "conversation_no")
	btnSecretYes     = secretMenu.Data("Yes", "secret_yes")
	btnSecretNo      = secretMenu.Data("No", "secret_no")
)

func init() {
	conversationMenu.Inline(conversationMenu.Row(btnYes, btnNo))
	secretMenu.Inline(secretMenu.Row(btnSecretYes, btnSecretNo))
}

func handleConversation(ctx telebot.Context) error {
	return ctx.Send(`This conversation is only for the reviewer of a test task from devOps course!
By pressing 'Yes' you confirm that you're a reviewer`, conversationMenu)
}

func handleConversationYes(ctx telebot.Context) error {
	if err := ctx.Respond(); err != nil {
		return err
	}
	return ctx.Send(`Ok Mr./Mrs. Reviewer! Do you want to know the secret?
If yes then you must promise to give me the maximum points for this test.
Do you promise?`, secretMenu)
}

func handleConversationNo(ctx telebot.Context) error {
	if err := ctx.Respond(); err != nil {
		return err
	}
	return ctx.Send("Than you can explore other command by typing /help")
}

func handleSecretYes(ctx telebot.Context) error {
	if err := ctx.Respond(); err != nil {
		return err
	}
	return ctx.Send(
		`README.md was completely generated by AI. Everything else I wrote by my on hands!
And don't forget your promisse`,
	)
}

func handleSecretNo(ctx telebot.Context) error {
	if err := ctx.Respond(); err != nil {
		return err
	}
	return ctx.Send("Than you can explore another command by typing /help")
}
